-- Bank emails parsed by the read-inbox-messages function land here as drafts.
-- The user reviews them in the web app and saves them as movements or discards them.
-- Safe to re-run.

alter table category add column if not exists description text;

create table if not exists movement_draft (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  email_id text unique,
  amount numeric,
  currency text,
  type text,
  description text,
  category_id bigint references category (id) on delete set null,
  bank text,
  date timestamptz,
  subject text,
  created_at timestamptz not null default now()
);

create index if not exists movement_draft_user_id_idx on movement_draft (user_id);

alter table movement_draft enable row level security;

-- Inserts come from the edge function as postgres, which bypasses RLS.
drop policy if exists "Users can read their own drafts" on movement_draft;
create policy "Users can read their own drafts" on movement_draft
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Users can update their own drafts" on movement_draft;
create policy "Users can update their own drafts" on movement_draft
  for update to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own drafts" on movement_draft;
create policy "Users can delete their own drafts" on movement_draft
  for delete to authenticated using (auth.uid() = user_id);
